package com.pdfreader.app.cloud

import android.content.Context
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.GetCredentialException
import com.google.android.libraries.identity.googleid.GetGoogleIdOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.android.libraries.identity.googleid.GoogleIdTokenParsingException
import com.google.firebase.auth.FirebaseAuth
import com.google.firebase.auth.FirebaseUser
import com.google.firebase.auth.GoogleAuthProvider
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.tasks.await

/**
 * Real Google Sign-In implementation of [CloudAuthRepository] (PDF-011, DEC-003), backed by
 * Credential Manager (the current Android-recommended replacement for the deprecated
 * `GoogleSignInClient`) and Firebase Auth. Gated behind the real Firebase project having the
 * Google sign-in provider enabled and this app's debug/release SHA-1 fingerprints registered
 * — both done 2026-11-05 (see `docs/DECISIONS_AND_OPEN_QUESTIONS.md` DEC-003's consequences).
 *
 * [webClientId] must be the Firebase project's own auto-generated Web client id
 * (`R.string.default_web_client_id`, generated by the `google-services` Gradle plugin from
 * `google-services.json`'s `oauth_client` entry) — any other client id silently fails Google
 * ID token verification server-side.
 */
class FirebaseCloudAuthRepository(
    private val context: Context,
    private val webClientId: String,
    private val firebaseAuth: FirebaseAuth = FirebaseAuth.getInstance(),
) : CloudAuthRepository {

    private val credentialManager = CredentialManager.create(context)

    private val _currentUser = MutableStateFlow(firebaseAuth.currentUser?.toCloudUser())
    override val currentUser: StateFlow<CloudUser?> = _currentUser

    init {
        firebaseAuth.addAuthStateListener { auth -> _currentUser.value = auth.currentUser?.toCloudUser() }
    }

    /**
     * Launches the system Credential Manager Google account picker, then exchanges the
     * resulting Google ID token for a Firebase session via [signInWithGoogle]. Call this
     * (not [signInWithGoogle] directly) for an actual user-initiated sign-in — it is the
     * only way to obtain a real [idToken] in the first place.
     */
    suspend fun signIn(): Result<CloudUser> {
        val option = GetGoogleIdOption.Builder()
            .setFilterByAuthorizedAccounts(false)
            .setServerClientId(webClientId)
            .build()
        val request = GetCredentialRequest.Builder().addCredentialOption(option).build()

        return try {
            val response = credentialManager.getCredential(context, request)
            val credential = response.credential
            if (credential !is CustomCredential ||
                credential.type != GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL
            ) {
                return Result.failure(IllegalStateException("Unexpected credential type from Credential Manager."))
            }
            val googleIdTokenCredential = GoogleIdTokenCredential.createFrom(credential.data)
            signInWithGoogle(googleIdTokenCredential.idToken)
        } catch (e: GetCredentialException) {
            Result.failure(e)
        } catch (e: GoogleIdTokenParsingException) {
            Result.failure(e)
        }
    }

    override suspend fun signInWithGoogle(idToken: String): Result<CloudUser> = try {
        val firebaseCredential = GoogleAuthProvider.getCredential(idToken, null)
        val result = firebaseAuth.signInWithCredential(firebaseCredential).await()
        val user = result.user?.toCloudUser()
        if (user != null) Result.success(user) else Result.failure(IllegalStateException("Sign-in succeeded but returned no user."))
    } catch (e: Exception) {
        Result.failure(e)
    }

    override suspend fun signOut() {
        firebaseAuth.signOut()
    }
}

private fun FirebaseUser.toCloudUser() = CloudUser(uid = uid, displayName = displayName, email = email)
